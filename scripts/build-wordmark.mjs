// Builds src/brand/wordmark.generated.ts from Geist Bold glyph outlines.
// Run: node scripts/build-wordmark.mjs
// Tune TRACKING / PAIR_ADJUST by eye, then re-run.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const fontPath = path.join(root, 'node_modules/geist/dist/fonts/geist-sans/Geist-Bold.ttf');
const font = opentype.parse(fs.readFileSync(fontPath).buffer);

const TEXT = 'trygrowency';
const SIZE = 1000; // design units (1 em)
const TRACKING = -38; // global tightening, in units per em
// Optical pair adjustments (units per em), applied after kerning + tracking.
const PAIR_ADJUST = { tr: 4, ry: 6, yg: 0, gr: 4, ro: 10, ow: -10, we: -12, en: -4, nc: -6, cy: -10 };

const glyphs = font.stringToGlyphs(TEXT);
const scale = SIZE / font.unitsPerEm;
let x = 0;
const letters = [];
for (let i = 0; i < glyphs.length; i++) {
  const g = glyphs[i];
  const ch = TEXT[i];
  if (i > 0) {
    const prev = glyphs[i - 1];
    x += font.getKerningValue(prev, g) * scale + TRACKING + (PAIR_ADJUST[TEXT[i - 1] + ch] ?? 0);
  }
  const p = g.getPath(x, 0, SIZE);
  const bb = p.getBoundingBox();
  letters.push({
    ch,
    x: +x.toFixed(2),
    advance: +(g.advanceWidth * scale).toFixed(2),
    d: p.toPathData(2),
    bbox: [bb.x1, bb.y1, bb.x2, bb.y2].map((v) => +v.toFixed(2)),
  });
  x += g.advanceWidth * scale;
}

// The final "y" is redrawn: Geist's hooked tail is replaced by the right arm
// running straight down into the descender, ending in a diagonal terminal
// cut at the same angle as the Growency mark's lower edge (MARK_CUT_SLOPE in
// src/brand/mark.ts). Coordinates are glyph-relative (Geist Bold, 1000 upm).
const CUT_SLOPE = 0.62; // rise over run of the terminal cut
const y = letters[letters.length - 1];
{
  const o = y.x;
  const armDx = 206 / 587; // horizontal run per unit of descent along the right arm
  const depth = 168; // descender depth below baseline
  const leftTop = [250, -27]; // where the left arm meets the descender stroke
  const bottomLeftX = leftTop[0] - armDx * (depth - leftTop[1]);
  // Intersect the cut line with the arm's outer edge (through 565,-536).
  // cut: yy = depth - CUT_SLOPE * (x - bottomLeftX)
  const ox = (565 - armDx * (depth + 536) - armDx * CUT_SLOPE * bottomLeftX) / (1 - armDx * CUT_SLOPE);
  const oy = depth - CUT_SLOPE * (ox - bottomLeftX);
  const pts = [
    [21, -536], [174, -536], [297, -167], [412, -536], [565, -536],
    [ox, oy], [bottomLeftX, depth], leftTop, [209, -27],
  ];
  y.d = 'M' + pts.map(([a, b]) => `${(a + o).toFixed(2)} ${b.toFixed(2)}`).join('L') + 'Z';
  y.bbox = [21 + o, -536, 565 + o, depth];
}
const minX = Math.min(...letters.map((l) => l.bbox[0]));
const maxX = Math.max(...letters.map((l) => l.bbox[2]));
const minY = Math.min(...letters.map((l) => l.bbox[1]));
const maxY = Math.max(...letters.map((l) => l.bbox[3]));

const out = `// AUTO-GENERATED by scripts/build-wordmark.mjs — do not edit by hand.
// Geist Bold outlines, tightened tracking, custom diagonal cut on the final y.
export interface WordmarkLetter { ch: string; x: number; advance: number; d: string; bbox: [number, number, number, number] }
export const WORDMARK_TEXT = ${JSON.stringify(TEXT)};
/** viewBox in design units (y down, baseline at 0). */
export const WORDMARK_VIEWBOX = ${JSON.stringify([+(minX - 6).toFixed(1), +(minY - 6).toFixed(1), +(maxX - minX + 12).toFixed(1), +(maxY - minY + 12).toFixed(1)])} as const;
export const WORDMARK_LETTERS: WordmarkLetter[] = ${JSON.stringify(letters, null, 1)};
`;
fs.writeFileSync(path.join(root, 'src/brand/wordmark.generated.ts'), out);
console.log('wordmark width', (maxX - minX).toFixed(0), 'height', (maxY - minY).toFixed(0));
